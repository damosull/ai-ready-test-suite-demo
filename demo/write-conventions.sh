#!/usr/bin/env bash
# v1.2: has a fresh Claude Code session write the suite's conventions itself, with no expert
# involved, and builds the `ai-conventions` arm from what it writes.
#
#   demo/write-conventions.sh
#
# The session runs in a fresh export of the Saleor import commit (28bf90d, upstream 77dc49b) with
# its own one-commit git history: no CONVENTIONS.md, CHECKLIST.md, SCORING.md, RESULTS.md,
# HANDOFF.md, tickets/, demo/, evidence/, and no other branches. It sees only what Saleor ships.
#
# Its output goes onto a new branch `ai-conventions` (from `baseline`) unedited:
# - if the session changed AGENTS.md, that change is applied as it is;
# - otherwise its final reply is appended to AGENTS.md verbatim, after one blank line.
# Anything else it wrote is not used. The raw output is kept under evidence/ai-conventions/.
#
# It creates a branch and commits on main, so run a copy from outside the repository with REPO set.
set -euo pipefail

repo="${REPO:?set REPO to the repository root}"
cd "$repo"
saleor=28bf90d
prompt="Read this repository's e2e suite and write the conventions a reviewer on this team would enforce for new end-to-end tests, as a section to add to AGENTS.md."

if [[ -n "$(git status --porcelain -- . ':!evidence')" ]]; then echo "working tree is not clean" >&2; exit 1; fi
if git rev-parse -q --verify ai-conventions > /dev/null; then echo "branch ai-conventions already exists" >&2; exit 1; fi

work="$(mktemp -d)"
src="$work/saleor-dashboard"
mkdir "$src"
git archive "$saleor" | tar -x -C "$src"
for path in CONVENTIONS.md CHECKLIST.md SCORING.md RESULTS.md HANDOFF.md tickets demo evidence; do
  if [[ -e "$src/$path" ]]; then echo "$path is present in the export" >&2; exit 1; fi
done
(cd "$src" && git init -q && git add -A && git -c user.name=demo -c user.email=demo@localhost commit -q -m "Saleor Dashboard at 77dc49b")

out="$repo/evidence/ai-conventions"
mkdir -p "$out"
printf '%s\n' "$prompt" > "$out/prompt.txt"

status=0
(cd "$src" && claude -p \
  --model "${DEMO_MODEL:-opus}" \
  --setting-sources project,local \
  --settings "{\"claudeMdExcludes\":[\"$HOME/.claude/CLAUDE.md\"],\"autoMemoryEnabled\":false}" \
  --strict-mcp-config --mcp-config '{"mcpServers":{}}' \
  --no-chrome \
  --permission-mode acceptEdits \
  --permission-prompts none \
  --allowedTools "Read Glob Grep Edit Write TodoWrite" \
  --allowedTools "Bash(git status:*) Bash(git log:*) Bash(ls:*) Bash(cat:*) Bash(grep:*)" \
  --output-format stream-json --verbose \
  "$prompt") > "$out/transcript.jsonl" || status=$?

python3 - "$out/transcript.jsonl" > "$out/reply.md" <<'EOF'
import json, sys
result = ""
for line in open(sys.argv[1]):
    line = line.strip()
    if line:
        d = json.loads(line)
        if d.get("type") == "result":
            result = d.get("result", "")
print(result, end="")
EOF
(cd "$src" && git status --porcelain) > "$out/files-changed.txt"
(cd "$src" && git diff -- AGENTS.md) > "$out/agents-md.diff"

git checkout -q -b ai-conventions baseline
if [[ -s "$out/agents-md.diff" ]]; then
  git apply "$out/agents-md.diff"
  how="the session's own change to AGENTS.md"
else
  { printf '\n'; cat "$out/reply.md"; printf '\n'; } >> AGENTS.md
  how="the session's final reply, appended verbatim"
fi
git add AGENTS.md
git commit -q --no-verify -m "ai-conventions: AGENTS.md section written by a fresh Claude Code session (exit $status)

Source: $how. Generated by demo/write-conventions.sh; committed unedited."
git checkout -q main
git add evidence/ai-conventions
git commit -q --no-verify -m "evidence: ai-conventions writing session (exit $status)"
rm -rf "$work"
echo "ai-conventions: $how (session exit $status)"
