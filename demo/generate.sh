#!/usr/bin/env bash
# Generates the tests for one ticket on one branch, in a fresh Claude Code session, and
# commits whatever the session wrote, unedited, to its own branch `<branch>-t<ticket>`
# (round 2 onwards: `<branch>-r<round>-t<ticket>`). Every ticket starts from the setup
# itself, never from another ticket's output.
#
#   demo/generate.sh <baseline|with-setup> <01..05> [round]
#
# It checks out the branch, so run a copy from outside the repository with REPO set:
#   cp demo/generate.sh /tmp/ && REPO=$PWD /tmp/generate.sh baseline 01
#
# The demo's own method files are taken off disk for the session, so the AI tool cannot read
# how it will be scored or what will be broken. The baseline also does not see
# CONVENTIONS.md or CHECKLIST.md: those are the knowledge the setup encodes, and are part of
# the with-setup branch's setup.
set -euo pipefail

branch="$1"
ticket="$2"
round="${3:-1}"
repo="${REPO:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$repo"

case "$branch" in
  baseline)
    hide=(CONVENTIONS.md CHECKLIST.md SCORING.md RESULTS.md demo/breaks demo/prompts/review.md evidence)
    mcp="demo/playwright-mcp.json"
    ;;
  with-setup)
    hide=(SCORING.md RESULTS.md demo/breaks demo/prompts/review.md evidence)
    mcp="demo/no-mcp.json"
    ;;
  *) echo "branch must be baseline or with-setup" >&2; exit 1 ;;
esac

if [[ -n "$(git status --porcelain -- . ':!evidence')" ]]; then
  echo "working tree is not clean" >&2
  exit 1
fi

if [[ "$round" == "1" ]]; then
  out="$branch-t$ticket"
else
  out="$branch-r$round-t$ticket"
fi
git checkout -q -B "$out" "$branch"

# Copies kept outside the repository, because the files are about to leave it.
work="$(mktemp -d)"
cp demo/claude-session.sh "$work/"
cp "$mcp" "$work/mcp.json"
prompt="$(sed "s#{{TICKET}}#tickets/$ticket.md#" "demo/prompts/$branch.md")"
log="$work/transcript.jsonl"

for path in "${hide[@]}"; do
  rm -rf "$path"
done

status=0
REPO="$repo" "$work/claude-session.sh" "$log" "$work/mcp.json" "$prompt" || status=$?

for path in "${hide[@]}"; do
  git checkout -q -- "$path" 2>/dev/null || true
done

mkdir -p "evidence/transcripts/round-$round"
cp "$log" "evidence/transcripts/round-$round/$branch-$ticket.jsonl"
git add -A
git commit -q --no-verify -m "$branch: ticket $ticket (round $round, session exit $status)

Generated by demo/generate.sh; committed as the session left it."
rm -rf "$work"
git checkout -q main
echo "$out: session exit $status"
